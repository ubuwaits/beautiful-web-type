"""Generate index-only WOFF2 subsets; full specimen fonts are never modified.

Requires fonttools and brotli. Run after adding a font, changing its name,
or updating its CSS/font assets. Generated assets are committed, so site builds
need neither Python nor fonttools. Unchanged inputs reuse the existing subset.
"""

import hashlib
import json
import re
import subprocess
from pathlib import Path

import fontTools
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "public/assets/font-previews"
CSS_OUTPUT = ROOT / "app/fonts/previews.css"
MANIFEST = OUTPUT / "manifest.json"


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def regular_face(slug):
    css_path = ROOT / "app/fonts" / f"{slug}.css"
    css = css_path.read_text()
    # Follow the family used by the slug class, not another family in the file.
    family = re.search(rf"--{re.escape(slug)}:\s*['\"]([^'\"]+)", css).group(1)
    matches = []
    for block in re.findall(r"@font-face\s*\{([^}]+)\}", css):
        props = dict(re.findall(r"([\w-]+)\s*:\s*([^;]+);", block))
        if props["font-family"].strip("\"'").casefold() != family.casefold() or props.get("font-style", "normal") != "normal":
            continue
        weights = [float(value) for value in props.get("font-weight", "400").split()]
        if min(weights) <= 400 <= max(weights):
            url = re.search(r"url\(['\"]?([^'\")]+)", props["src"]).group(1).split("?")[0]
            matches.append((url, props))
    if len(matches) != 1:
        raise ValueError(f"Expected one regular upright CSS face for {slug}, found {matches}")
    return (*matches[0], css_path)


def build_preview(source, target, slug, text):
    with TTFont(source, recalcTimestamp=False) as font:
        options = subset.Options()
        options.name_IDs = ["*"]  # Preserve copyright, license, and axis metadata.
        options.name_languages = ["*"]
        if slug == "commit-mono":
            options.layout_features.append("ss05")  # Smart Kerning on catalog cards.
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(text=text)
        subsetter.subset(font)
        # Distinguish these derived, restricted-character fonts from the full family.
        family = f"BWT Preview {slug}"
        names = {1: family, 2: "Regular", 3: family, 4: family,
                 6: f"BWTPreview-{slug}", 16: family, 17: "Regular", 21: family, 22: "Regular", 25: f"BWTPreview-{slug}"}
        for record in font["name"].names:
            if record.nameID in names:
                font["name"].setName(names[record.nameID], record.nameID, record.platformID, record.platEncID, record.langID)
        font.flavor = "woff2"
        font.recalcTimestamp = False
        font.save(target)


def main():
    # Read the typed records through the project's existing TS loader.
    records = json.loads(subprocess.check_output([
        "node", "--import", "tsx", "-e",
        'const {typefaceData}=require("./content/typefaces");'
        'console.log(JSON.stringify(typefaceData.map(({slug,name})=>({slug,name}))));',
    ], cwd=ROOT, text=True))
    OUTPUT.mkdir(parents=True, exist_ok=True)
    previous = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else {}
    manifest = {}
    css = ["/* Generated by scripts/prepare-font-previews.py. Index cards only. */\n"]
    generator = sha256(Path(__file__).read_bytes())
    changed = 0
    source_bytes = 0
    preview_bytes = 0
    for record in sorted(records, key=lambda entry: entry["slug"]):
        slug = record["slug"]
        text = record["name"]
        url, properties, css_path = regular_face(slug)
        source = ROOT / "public" / url.lstrip("/")
        target = OUTPUT / f"{slug}.woff2"
        entry = {"source": url, "sourceHash": sha256(source.read_bytes()),
                 "text": text, "cssHash": sha256(css_path.read_bytes()), "generatorHash": generator, "toolVersion": fontTools.__version__}
        old = previous.get(slug, {})
        if (not target.exists() or any(old.get(key) != value for key, value in entry.items())
                or old.get("previewHash") != sha256(target.read_bytes())):
            build_preview(source, target, slug, text)
            changed += 1
        entry["previewHash"] = sha256(target.read_bytes())
        manifest[slug] = entry
        source_bytes += source.stat().st_size
        preview_bytes += target.stat().st_size
        stretch = f'  font-stretch: {properties["font-stretch"]};\n' if "font-stretch" in properties else ""
        css.append(f'''@font-face {{
  font-family: "BWT Preview {slug}";
  font-style: normal;
  font-weight: {properties.get("font-weight", "400")};
{stretch}  src: url("/assets/font-previews/{slug}.woff2") format("woff2");
}}
''')
    # Remove only generated previews for families no longer in the collection.
    for stale in previous.keys() - manifest.keys():
        (OUTPUT / f"{stale}.woff2").unlink(missing_ok=True)
    MANIFEST.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
    CSS_OUTPUT.write_text("\n".join(css))
    print(f"{len(manifest)} previews ({changed} regenerated): {source_bytes:,} → {preview_bytes:,} bytes")


if __name__ == "__main__":
    main()
